ALTER TABLE business
  ADD COLUMN sello_url VARCHAR(255) NULL;

CREATE TABLE IF NOT EXISTS agents (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id INT UNSIGNED NOT NULL,
  name VARCHAR(150) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_agents_user (user_id),
  CONSTRAINT fk_agents_user FOREIGN KEY (user_id)
    REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

ALTER TABLE sales
  ADD COLUMN agent_id INT UNSIGNED NULL,
  ADD COLUMN seller_name VARCHAR(150) NULL,
  ADD CONSTRAINT fk_sales_agent FOREIGN KEY (agent_id)
    REFERENCES agents (id) ON DELETE SET NULL;
